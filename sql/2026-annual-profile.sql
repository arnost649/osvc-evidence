CREATE TABLE IF NOT EXISTS osvc_profile (
 id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
 data JSON NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS osvc_year_profiles (
 tax_year SMALLINT UNSIGNED NOT NULL PRIMARY KEY,
 data JSON NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS annual_closures (
 tax_year SMALLINT UNSIGNED NOT NULL PRIMARY KEY,
 ruleset_id VARCHAR(100) NOT NULL,
 ruleset JSON NOT NULL,
 snapshot JSON NOT NULL,
 pdf_attachment_id BIGINT UNSIGNED NULL,
 closed_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
